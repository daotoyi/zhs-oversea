/** 按语种取中文文案（英文返回 undefined，由调用方回落） */
export function zh<T>(hans: T | undefined, locale: Locale): T | undefined {
  if (hans === undefined) return undefined;
  if (locale === 'zh-Hant') {
    if (typeof hans === 'string') return toTraditional(hans) as unknown as T;
    if (Array.isArray(hans)) return (hans as string[]).map(toTraditional) as unknown as T;
  }
  return hans;
}
